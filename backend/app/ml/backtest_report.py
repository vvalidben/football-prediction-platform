def _cell(metrics: Mapping[str, float], key: str, decimals: int, percent: bool) -> str:
    if key not in metrics:
        return DASH
    value = metrics[key] * (100 if percent else 1)
    return f"{value:.{decimals}f}{'%' if percent else ''}"


def _variant(model: str, variant: str) -> str:
    return model if variant == "none" else f"{model} + {variant}"


def _heading(variant: str) -> str:
    return "raw" if variant == "none" else variant


def _table(
    rows: Sequence[tuple[str, Mapping[str, float]]],
    columns: Sequence[tuple[str, str, int, bool]],
    first: str,
) -> list[str]:
    lines = [
        f"| {first} | " + " | ".join(label for _, label, _, _ in columns) + " |",
        "| --- |" + " ---: |" * len(columns),
    ]
    for name, metrics in rows:
        cells = " | ".join(_cell(metrics, k, d, p) for k, _, d, p in columns)
        lines.append(f"| {name} | {cells} |")
    return lines


def render_backtest_report(
    result: BacktestResult,
    *,
    competitions: Mapping[int, str] | None = None,
    seasons: Mapping[int, str] | None = None,
    title: str = "Backtest",
) -> str:
    competitions = competitions or {}
    seasons = seasons or {}
    config = result.config
    predicted = [s for s in result.steps if not s.skipped]
    hours = config.result_delay / timedelta(hours=1)
    every = config.retrain_every / timedelta(days=1)
    window = (
        "expanding (all earlier matches)"
        if config.window == "expanding"
        else f"rolling ({config.window_days} days)"
    )
    lines = [
        f"# {title}",
        "",
        f"Feature set `{result.feature_set_version}`. Generated by `python -m app.ml backtest`.",
        "",
        "## Protocol",
        "",
        f"- Period: {config.start.date()} to "
        f"{config.end.date() if config.end else 'the last match'}; "
        f"{len(predicted)} retraining steps, one every {every:g} days.",
        f"- Training window: {window}. At each step time t, models are fitted only on "
        f"matches whose results were known at t (kickoff + {hours:g} h <= t), and "
        "predict the matches kicking off before the next step, from feature snapshots "
        "taken at kickoff.",
        f"- Warm-up: training rows need both teams to have >= {config.min_team_history} "
        f"rated matches; steps with fewer than {config.min_training_matches} training "
        f"matches predict nothing ({result.skipped_matches} matches skipped).",
        "- Calibration (" + ", ".join(v for v in config.calibration if v != "none") + "): "
        "fitted at each step on the model's own earlier backtest predictions whose results "
        f"were known at t; used once at least {config.min_calibration_matches} exist, "
        "otherwise the raw probabilities are kept.",
        "- Models and fixed hyperparameters: "
        + "; ".join(f"`{m.label}`" for m in result.models)
        + ". Hyperparameters chosen on data overlapping the backtest period are a "
        "look-ahead this framework cannot detect.",
        "",
        "## Overall",
        "",
    ]
    overall = [
        (_variant(model, variant), result.metrics(model, variant))
        for model, variant in result.variants
    ]
    lines += _table(overall, OVERALL, "Model")
    lines += _calibration_section(result)
    lines += ["", "## By season", ""]
    for key, names, heading in (
        ("season_id", seasons, "Season"),
        ("competition_id", competitions, "Competition"),
    ):
        if key == "competition_id":
            lines += ["", "## By competition", ""]
        for model, variant in result.variants:
            grouped = result.grouped(model, variant, key)
            rows = [(names.get(g, str(g)), m) for g, m in grouped.items()]
            lines += ["", f"**{_variant(model, variant)}**", ""]
            lines += _table(rows, GROUPED, heading)
    lines += ["", "## By prediction type", ""]
    for spec in result.models:
        variants = [v for m, v in result.variants if m == spec.label]
        metrics = {v: result.metrics(spec.label, v) for v in variants}
        lines += [
            "",
            f"**{spec.label}**",
            "",
            "| Prediction | Metric | " + " | ".join(_heading(v) for v in variants) + " |",
            "| --- | --- |" + " ---: |" * len(variants),
        ]
        for market, columns in MARKETS:
            for key, label, decimals, percent in columns:
                cells = " | ".join(_cell(metrics[v], key, decimals, percent) for v in variants)
                lines.append(f"| {market} | {label} | {cells} |")
    return "\n".join(lines) + "\n"


def _calibration_section(result: BacktestResult) -> list[str]:
    methods = [v for v in result.config.calibration if v != "none"]
    lines = ["", "## Calibration", ""]
    if not methods or "none" not in result.config.calibration:
        return [*lines, "Raw and calibrated variants were not both run."]
    lines += [
        "Compared on the matches where a calibrator was active (enough earlier "
        "predictions with known results). Differences are calibrated minus raw, with a "
        "95% paired bootstrap interval (negative = calibration helped).",
        "",
        "| Model | Calibration | Matches | Raw log loss | Calibrated log loss | Difference "
        "| 95% interval | Raw ECE | Calibrated ECE |",
        "| --- | --- | ---: | ---: | ---: | ---: | --- | ---: | ---: |",
    ]
    for spec in result.models:
        for method in methods:
            calibrated = [
                r for r in result.records if r.model == spec.label and r.variant == method
            ]
            active = {r.example.match_id for r in calibrated if r.calibrated_on}
            if not active:
                lines.append(f"| {spec.label} | {method} | 0 |" + f" {DASH} |" * 6)
                continue
            raw = result.metrics(spec.label, "none", _among(active))
            cal = result.metrics(spec.label, method, _among(active))
            raw_losses = _losses(result, spec.label, "none", active)
            cal_losses = _losses(result, spec.label, method, active)
            gain = paired_bootstrap(cal_losses, raw_losses)
            lines.append(
                f"| {spec.label} | {method} | {len(active)} | {raw['log_loss']:.4f} "
                f"| {cal['log_loss']:.4f} | {gain['difference']:+.4f} "
                f"| [{gain['low']:+.4f}, {gain['high']:+.4f}] "
                f"| {raw['ece']:.4f} | {cal['ece']:.4f} |"
            )
    lines += [
        "",
        "### Reliability (raw probabilities)",
        "",
        "Predicted probability bins against observed frequency, over all backtest "
        "predictions. A well-calibrated model has observed close to predicted in every bin.",
    ]
    for spec in result.models:
        chosen = [r for r in result.records if r.model == spec.label and r.variant == "none"]
        probs = np.array([r.prediction.outcomes for r in chosen])
        outcomes = np.array([r.example.outcome for r in chosen])
        lines += [
            "",
            f"**{spec.label}**",
            "",
            "| Bin | Home: n | predicted | observed | Draw: n | predicted | observed "
            "| Away: n | predicted | observed |",
            "| --- |" + " ---: |" * 9,
        ]
        tables = [
            {row["low"]: row for row in reliability(probs[:, k], outcomes == k)}
            for k in (HOME, DRAW, AWAY)
        ]
        for low in sorted({low for table in tables for low in table}):
            cells = []
            for table in tables:
                row = table.get(low)
                cells += (
                    [
                        f"{int(row['count'])}",
                        f"{row['mean_predicted']:.3f}",
                        f"{row['observed']:.3f}",
                    ]
                    if row
                    else ["0", DASH, DASH]
                )
            lines.append(f"| {low:.1f}{DASH}{low + 0.1:.1f} | " + " | ".join(cells) + " |")
    return lines


def _among(match_ids: set[int]) -> Callable[[BacktestRecord], bool]:
    return lambda r: r.example.match_id in match_ids


def _losses(result: BacktestResult, model: str, variant: str, match_ids: set[int]) -> list[float]:
    predictions, data = result.select(model, variant, _among(match_ids))
    losses: list[float] = match_log_losses(predictions, data).tolist()
    return losses
